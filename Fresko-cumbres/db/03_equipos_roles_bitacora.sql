-- ============================================================
-- Cambia el modelo de permisos de 4 banderas a 2 roles:
--   admin  -> entra al dashboard completo + todo lo de equipo
--   equipo -> solo /lista y /puestos (pasar lista, altas, datos, INE)
-- Agrega equipos (A-D con nombre editable), suplencias y bitácora privada.
-- ============================================================

-- ---------- 1. ROLES ----------
alter table dashboard_acceso add column if not exists rol text;
update dashboard_acceso set rol = case when admin then 'admin' else 'equipo' end where rol is null;
alter table dashboard_acceso alter column rol set default 'equipo';
alter table dashboard_acceso alter column rol set not null;
alter table dashboard_acceso drop constraint if exists dashboard_acceso_rol_chk;
alter table dashboard_acceso add constraint dashboard_acceso_rol_chk check (rol in ('admin','equipo'));

alter table invitaciones add column if not exists rol text;
update invitaciones set rol = case when admin then 'admin' else 'equipo' end where rol is null;
alter table invitaciones alter column rol set default 'equipo';
alter table invitaciones alter column rol set not null;
alter table invitaciones drop constraint if exists invitaciones_rol_chk;
alter table invitaciones add constraint invitaciones_rol_chk check (rol in ('admin','equipo'));

-- ---------- 2. EQUIPOS ----------
create table if not exists equipos (
  id          smallint generated by default as identity primary key,
  campana     text not null default 'FRESKO-CUMBRES-SEP26',
  clave       text not null,
  nombre      text not null,
  color       text,
  punto_clave text,
  activo      boolean not null default true,
  creado_en   timestamptz not null default now(),
  unique (campana, clave)
);

insert into equipos (clave, nombre, color) values
  ('A','Equipo A','#0B5D2E'),
  ('B','Equipo B','#F2681F'),
  ('C','Equipo C','#2E6FA3'),
  ('D','Equipo D','#8A4FBF')
on conflict (campana, clave) do nothing;

alter table candidatos add column if not exists equipo_id smallint references equipos(id) on delete set null;
create index if not exists idx_cand_equipo on candidatos(equipo_id);

-- ---------- 3. FOTO DE INE ----------
alter table candidatos add column if not exists foto_ine_path text;
alter table candidatos add column if not exists foto_ine_en   timestamptz;

-- ---------- 4. SUPLENCIAS ----------
create table if not exists suplencias (
  id             bigint generated always as identity primary key,
  campana        text not null default 'FRESKO-CUMBRES-SEP26',
  dia            date not null default ((now() at time zone 'America/Monterrey')::date),
  folio_ausente  text not null,
  folio_suplente text not null,
  equipo_id      smallint references equipos(id),
  motivo         text,
  creado_por     uuid,
  creado_en      timestamptz not null default now(),
  unique (campana, dia, folio_ausente)
);

-- ---------- 5. BITACORA (privada: sin políticas RLS, nadie la lee por API) ----------
create table if not exists bitacora (
  id            bigint generated always as identity primary key,
  momento       timestamptz not null default now(),
  actor         uuid,
  actor_correo  text,
  actor_nombre  text,
  accion        text not null,
  folio         text,
  detalle       jsonb not null default '{}'::jsonb
);
create index if not exists idx_bitacora_momento on bitacora(momento desc);
create index if not exists idx_bitacora_folio   on bitacora(folio);

alter table equipos    enable row level security;
alter table suplencias enable row level security;
alter table bitacora   enable row level security;

drop policy if exists equipos_lectura on equipos;
create policy equipos_lectura on equipos for select to authenticated using (true);
drop policy if exists suplencias_lectura on suplencias;
create policy suplencias_lectura on suplencias for select to authenticated using (true);
