-- ---------- 6. HELPERS ----------
create or replace function public.es_admin() returns boolean
language sql stable security definer set search_path to 'public' as $fn$
  select coalesce((select rol = 'admin' from dashboard_acceso where user_id = auth.uid()), false);
$fn$;

create or replace function public.puede_lista() returns boolean
language sql stable security definer set search_path to 'public' as $fn$
  select exists (select 1 from dashboard_acceso where user_id = auth.uid());
$fn$;

create or replace function public.anotar(
  p_accion text, p_folio text default null, p_detalle jsonb default '{}'::jsonb)
returns void language plpgsql security definer set search_path to 'public' as $fn$
declare v_correo text; v_nombre text;
begin
  select correo, nombre into v_correo, v_nombre from dashboard_acceso where user_id = auth.uid();
  insert into bitacora (actor, actor_correo, actor_nombre, accion, folio, detalle)
  values (auth.uid(), v_correo, v_nombre, p_accion, p_folio, coalesce(p_detalle,'{}'::jsonb));
end; $fn$;

revoke all on function public.anotar(text, text, jsonb) from public;
revoke all on function public.anotar(text, text, jsonb) from anon;
revoke all on function public.anotar(text, text, jsonb) from authenticated;

-- ---------- 7. PERMISOS (reescritos sobre rol) ----------
create or replace function public.mi_permiso(p_cual text) returns boolean
language sql stable security definer set search_path to 'public' as $fn$
  select case p_cual
           when 'admin'      then public.es_admin()
           when 'dinero'     then public.es_admin()
           when 'candidatos' then public.es_admin()
           when 'lista'      then public.puede_lista()
           else false
         end;
$fn$;

create or replace function public.mis_permisos() returns jsonb
language sql stable security definer set search_path to 'public' as $fn$
  select coalesce(
    (select jsonb_build_object(
        'nombre', nombre, 'correo', correo, 'rol', rol,
        'admin', rol = 'admin', 'lista', true,
        'candidatos', rol = 'admin', 'dinero', rol = 'admin')
     from dashboard_acceso where user_id = auth.uid()),
    jsonb_build_object('rol', null, 'admin', false, 'lista', false,
                       'candidatos', false, 'dinero', false));
$fn$;

create or replace function public.puede_ver_dashboard() returns boolean
language sql stable security definer set search_path to 'public' as $fn$
  select public.puede_lista();
$fn$;

create or replace function public.reclamar_primer_admin() returns jsonb
language plpgsql security definer set search_path to 'public' as $fn$
declare v_correo text;
begin
  if auth.uid() is null then raise exception 'SIN_SESION'; end if;
  if exists (select 1 from dashboard_acceso where rol = 'admin') then
    return jsonb_build_object('ok', false, 'motivo','YA_HAY_ADMIN');
  end if;
  select email into v_correo from auth.users where id = auth.uid();
  insert into dashboard_acceso (user_id, nombre, correo, rol, ver_candidatos, ver_dinero, pasar_lista, admin)
  values (auth.uid(), 'Administrador', v_correo, 'admin', true, true, true, true)
  on conflict (user_id) do update set rol = 'admin', admin = true,
       ver_dinero = true, pasar_lista = true, ver_candidatos = true,
       correo = coalesce(dashboard_acceso.correo, excluded.correo);
  perform public.anotar('primer_admin', null, jsonb_build_object('correo', v_correo));
  return jsonb_build_object('ok', true, 'correo', v_correo);
end; $fn$;

create or replace function public.crear_invitacion(p jsonb) returns jsonb
language plpgsql security definer set search_path to 'public' as $fn$
declare v_tok uuid; v_rol text := lower(coalesce(p->>'rol','equipo'));
begin
  if not public.es_admin() then raise exception 'SIN_PERMISO'; end if;
  if v_rol not in ('admin','equipo') then v_rol := 'equipo'; end if;
  insert into invitaciones (correo, nombre, rol, creada_por,
                            ver_candidatos, ver_dinero, pasar_lista, admin)
  values (lower(btrim(p->>'correo')), nullif(btrim(coalesce(p->>'nombre','')),''),
          v_rol, auth.uid(),
          v_rol = 'admin', v_rol = 'admin', true, v_rol = 'admin')
  returning token into v_tok;
  perform public.anotar('invitacion_creada', null,
    jsonb_build_object('correo', p->>'correo', 'rol', v_rol));
  return jsonb_build_object('ok', true, 'token', v_tok, 'rol', v_rol);
end; $fn$;

create or replace function public.ver_invitacion(p_token uuid) returns jsonb
language sql stable security definer set search_path to 'public' as $fn$
  select coalesce((select jsonb_build_object(
      'ok', usada_en is null and expira_en > now(),
      'correo', correo, 'nombre', nombre, 'rol', rol,
      'usada', usada_en is not null, 'vencida', expira_en <= now())
    from invitaciones where token = p_token),
    jsonb_build_object('ok', false, 'no_existe', true));
$fn$;

create or replace function public.aceptar_invitacion(p_token uuid) returns jsonb
language plpgsql security definer set search_path to 'public' as $fn$
declare v record; v_correo text;
begin
  if auth.uid() is null then raise exception 'SIN_SESION'; end if;
  select * into v from invitaciones where token = p_token;
  if v.token is null then return jsonb_build_object('ok', false, 'motivo','NO_EXISTE'); end if;
  if v.usada_en is not null then return jsonb_build_object('ok', false, 'motivo','YA_USADA'); end if;
  if v.expira_en <= now() then return jsonb_build_object('ok', false, 'motivo','VENCIDA'); end if;

  select email into v_correo from auth.users where id = auth.uid();
  if lower(v_correo) <> lower(v.correo) then
    return jsonb_build_object('ok', false, 'motivo','CORREO_DISTINTO', 'esperado', v.correo);
  end if;

  insert into dashboard_acceso (user_id, nombre, correo, rol,
                                ver_candidatos, ver_dinero, pasar_lista, admin)
  values (auth.uid(), v.nombre, v.correo, v.rol,
          v.rol = 'admin', v.rol = 'admin', true, v.rol = 'admin')
  on conflict (user_id) do update set
    nombre = excluded.nombre, correo = excluded.correo, rol = excluded.rol,
    ver_candidatos = excluded.ver_candidatos, ver_dinero = excluded.ver_dinero,
    pasar_lista = excluded.pasar_lista, admin = excluded.admin;

  update invitaciones set usada_en = now() where token = p_token;
  perform public.anotar('invitacion_aceptada', null,
    jsonb_build_object('correo', v.correo, 'rol', v.rol));
  return jsonb_build_object('ok', true, 'nombre', v.nombre, 'rol', v.rol);
end; $fn$;
